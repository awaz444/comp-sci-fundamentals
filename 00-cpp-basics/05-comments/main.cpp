#include <iostream>

/*
 * This program demonstrates both comment styles.
 * Multi-line comments are great for file/function-level explanations.
 */
int main() {
    int score = 100; // single-line comment explaining this variable

    // The following block is intentionally simple to keep focus on comments.
    std::cout << "Score: " << score << '\n';

    return 0;
}
